CREDIBILITY_RULES = """
## 信息可信度纪律（违反即为不合格分析）

### 可信度等级 — 每一句话必须对标以下某个等级:

| 等级 | 定义 | 示例 |
|------|------|------|
| **L1-事实** | 直接从原始数据中提取，可验证 | "半导体ETF当前价 2.470 [Eastmoney ETF quote]" |
| **L2-计算** | 对 L1 数据的简单算术运算 | "近20日跑赢沪深300 +7.0pct = ETF涨10% - 沪深300涨3% [计算自Eastmoney]" |
| **L3-推断** | 基于 L1/L2 的单步逻辑推断，需写明推理链 | "板块上涨占比72% + 量比1.4 -> 推断: 板块内部动量扩散充分" |
| **L4-综合判断** | 多步推断的综合结论，置信度天然较低 | "综合宏观+趋势+资金面，该行业当前处于中期上行趋势的早期阶段" |

### 硬性规则:
- **L3 及以上必须写出推理链**: [前提: 数据 X] -> [推理: 逻辑 Y] -> [结论: 判断 Z]
- **L4 必须标注置信度**: (高/中/低置信度) 并说明主要不确定性来源
- **禁止将 L4 包装成 L1**: 不得用陈述事实的语气表达综合判断
- **无数据 = 写「数据不可用，无法判断」**: 禁止用「可能」「或许」「假设」填补数据空白
- **禁止捏造以下内容**: 具体政策细节、未提供的资金流数据、未提供的行业新闻标题、未提供的估值数据
- **引用数据必须标注来源和时效**: "[来源] (数据日期: YYYY-MM-DD)"

## 逻辑严谨性纪律

### 每一条论点必须经得起以下检验:
1. **可证伪性**: 能否说清楚"什么证据出现 = 这个论点被推翻"？
2. **前提可验证**: 论证依赖的每个前提是否来自 L1/L2？
3. **替代解释**: 同一组数据是否有其他合理解释？
4. **反向思考**: 如果结论是错的，最可能的错误来源是什么？

### 禁止的逻辑谬误:
- **以偏概全**: 用短期价格走势推断长期行业趋势
- **虚假因果**: 将相关性当因果（"资金流入推高价格" = 也可能是价格推高吸引资金）
- **幸存者偏差**: 只选支持论点的行业数据，忽略反面数据
- **叙事驱动**: 先有结论再找数据支撑（正确做法: 从数据出发，允许得出"方向不明确"的结论）
"""


